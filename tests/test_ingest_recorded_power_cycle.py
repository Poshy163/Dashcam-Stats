async def test_legacy_bootstrap_is_durable_and_excludes_the_already_captured_edge(saved_controller):
    path, load = saved_controller
    controller = load(record(version=1))
    first = observation(uptime=1000.1251)
    controller.observe(first)
    await finish(controller, "_anchor_task")
    expected_barrier = math.ceil(first.uptime_s * 1000) + 1000
    anchored = json.loads(path.read_text())
    assert anchored["schema_version"] == 2
    assert anchored["cycle_after_elapsed_ms"] == expected_barrier
    assert anchored["boot_id"] == BOOT and anchored["cancelled"] is True
    assert controller.native_cancelled(BOOT)

    # A new process must not reinterpret the carried edge as post-cancellation evidence.
    controller = load()
    controller.observe(observation(uptime=1001))
    await settle(controller)
    assert json.loads(path.read_text()) == anchored
    assert controller.native_cancelled(BOOT)

    # Only a subsequent real ON sample, strictly beyond the persisted barrier, qualifies.
    controller.observe(
        observation(uptime=1050, off_lower_elapsed_ms=1020_000, off_upper_elapsed_ms=1026_000)
    )
    await finish(controller, "_clear_task")
    assert not path.exists() and not controller.native_cancelled(BOOT)


async def test_same_edge_off_refreshes_never_move_legacy_barrier_forward(saved_controller):
    path, load = saved_controller
    controller = load(record(version=1))
    controller.observe(observation())
    await finish(controller, "_anchor_task")
    anchored = json.loads(path.read_text())
    for uptime in (1001, 1002, 1010):
        controller.observe(observation(uptime=uptime))
        await settle(controller)
        assert json.loads(path.read_text()) == anchored
    assert controller.native_cancelled(BOOT)


@pytest.mark.parametrize("successor", [record(barrier=950_000), record(generation=SUCCESSOR)])
async def test_queued_clear_cannot_erase_changed_barrier_or_successor(saved_controller, successor):
    path, load = saved_controller
    controller = load(record())
    controller.observe(observation())
    assert getattr(controller, "_clear_task", None) is not None
    # No await: replace the durable record before the queued asynchronous clear starts.
