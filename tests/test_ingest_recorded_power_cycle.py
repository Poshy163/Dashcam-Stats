async def test_failed_clear_keeps_durable_and_in_memory_admission_closed(
    saved_controller, monkeypatch
):
    path, load = saved_controller
    controller = load(record())
    unlink = Path.unlink

    def unavailable(current, *args, **kwargs):
        if current == path:
            raise OSError("simulated cancellation-record filesystem failure")
        return unlink(current, *args, **kwargs)

    monkeypatch.setattr(Path, "unlink", unavailable)
    controller.observe(observation())
    await finish(controller, "_clear_task")
    assert path.exists() and controller.native_cancelled(BOOT)
    assert load().native_cancelled(BOOT)


