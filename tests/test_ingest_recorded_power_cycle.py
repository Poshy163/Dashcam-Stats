async def finish(controller, attribute):
    task = getattr(controller, attribute, None)
    assert task is not None, f"Expected a bounded {attribute} task"
    await asyncio.wait_for(asyncio.shield(task), timeout=3)


async def settle(controller):
    for attribute in ("_anchor_task", "_clear_task"):
        task = getattr(controller, attribute, None)
        if task is not None:
            await asyncio.wait_for(asyncio.shield(task), timeout=3)


async def test_new_recorded_cycle_after_restart_clears_without_server_observed_on(saved_controller):
    path, load = saved_controller
    controller = load(record())
    assert controller.native_cancelled(BOOT)
    controller.observe(observation())
    await finish(controller, "_clear_task")
    assert not path.exists()
    assert not controller.native_cancelled(BOOT)
    assert not controller.snapshot()["requires_ignition_cycle"]
    assert not controller.snapshot()["active"]
    # A second server restart cannot resurrect a cancellation already cleared durably.
    assert not load().native_cancelled(BOOT)
    adb.shell.assert_not_awaited()


@pytest.mark.parametrize("barrier,clears", [(4000, True), (5000, False), (6000, False)])
async def test_actual_android_producer_preserves_edge_across_off_heartbeats(
    saved_controller, barrier, clears
):
    # Generated by the actual Android tracker and status serializer from synthetic
    # ON/OFF inputs. No real boot identity, footage, location or credentials are used.
    fixture = json.loads(
        (Path(__file__).parent / "fixtures/ingest/recorded-power-cycle-android.json").read_text()
    )
    short = adb.parse_sleep_deadline_evidence(fixture["after_short_cycle"])
    refreshed = adb.parse_sleep_deadline_evidence(fixture["after_off_heartbeats"])
    assert short is not None and refreshed is not None
    assert refreshed.observed_elapsed_ms > short.observed_elapsed_ms
    assert (short.off_lower_elapsed_ms, short.off_upper_elapsed_ms, short.window_s) == (
        refreshed.off_lower_elapsed_ms,
        refreshed.off_upper_elapsed_ms,
        refreshed.window_s,
    )

    path, load = saved_controller
    original = record(barrier=barrier)
    controller = load(original)
    status = IngestStatus()
    status.observe_unit_runtime(adb.RuntimeObservation(BOOT, 11, "off", 1200, 12, short))
    await settle(controller)
    if clears:
        assert not path.exists() and not controller.native_cancelled(BOOT)
        assert not status.radio_quieting_allowed()
        status.observe_unit_runtime(adb.RuntimeObservation(BOOT, 12, "off", 1200, 12, short))
        assert status.radio_quieting_allowed()
        remaining = status.sleep_countdown_remaining_s()
        deadline = status.sleep_deadline_uptime_s()
        assert 1201 <= deadline <= 1202  # Last ON at 5 s + 1200 s - bounded ADB margin.
    else:
        assert json.loads(path.read_text()) == original
        assert controller.native_cancelled(BOOT)

    # Changing next-timer policy to 300 seconds and refreshing OFF publication must
    # neither create a new edge nor change the producer's witnessed 1200-second window.
    status.observe_unit_runtime(adb.RuntimeObservation(BOOT, 26, "off", 300, 12, refreshed))
    await settle(controller)
    if clears:
        assert status.radio_quieting_allowed()
        assert 1100 < status.sleep_countdown_remaining_s() <= remaining - 13
        assert status.sleep_deadline_uptime_s() <= deadline
    else:
        assert json.loads(path.read_text()) == original
        assert controller.native_cancelled(BOOT)
        assert not status.radio_quieting_allowed()
        assert status.sleep_deadline_uptime_s() is None


